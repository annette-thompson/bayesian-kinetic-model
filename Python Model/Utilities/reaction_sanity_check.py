def run_all_checks(
    reactions: list[Any],
    moieties: list[str] | None = None,
    tol: float = DEFAULT_TOLERANCE,
    similarity_threshold: float = DEFAULT_SIMILARITY_THRESHOLD,
) -> dict[str, Any]:
    """Run all sanity checks on a pre-loaded reaction list. Includs carbon mass balance, 
    moiety balance, species continuity, reaction family chain consistency, name similarity, zero-rate 
    reactions, irreversible flow imbalances, and parameter value conflicts.

    Parameters
    ----------
    reactions            : list of ElementaryReaction objects from reaction_model_builder
    moieties             : moieties to balance-check in addition to carbon (default: CoA, ACP, NAD, NADP)
    tol                  : balance tolerance           (default: 1e-9)
    similarity_threshold : minimum SequenceMatcher ratio for name-similarity warnings
                           (default: 0.90)

    Returns
    -------
    dict with keys: reactions, balance, continuity, chain_sets, similarity,
                    zero_rates, irrev_flow, param_conflicts
    """
    if moieties is None:
        moieties = DEFAULT_MOIETIES

    print(f"Running sanity checks on {len(reactions)} expanded reactions\n")

    balance         = check_balances(reactions, moieties=moieties, tol=tol)
    continuity      = check_species_continuity(reactions)
    chain_sets      = check_chain_sets(reactions)
    similarity      = check_name_similarity(reactions, threshold=similarity_threshold)
    zero_rates      = check_zero_rates(reactions)
    irrev_flow      = check_irreversible_flow(reactions)
    param_conflicts = check_parameter_conflicts(reactions)

    print_balance_report(balance)
    print()
    print_continuity_report(continuity)
    print()
    print_chain_set_report(chain_sets)
    print()
    print_similarity_report(similarity)
    print()
    print_zero_rate_report(zero_rates)
    print()
    print_irreversible_flow_report(irrev_flow)
    print()
    print_parameter_conflict_report(param_conflicts)

    return {
        "reactions":       reactions,
        "balance":         balance,
        "continuity":      continuity,
        "chain_sets":      chain_sets,
        "similarity":      similarity,
        "zero_rates":      zero_rates,
        "irrev_flow":      irrev_flow,
        "param_conflicts": param_conflicts,
    }
