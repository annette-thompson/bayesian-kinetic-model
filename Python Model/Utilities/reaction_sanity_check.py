# Check 7 — Parameter conflicts
# ═══════════════════════════════════════════════════════════════════════════

def check_parameter_conflicts(reactions: list[_Reaction]) -> list[ParamConflictResult]:
    """Detect parameter names that are assigned different values across reactions.

    Checks both forward (rate_const_key / rate_const_value) and reverse
    (rvs_rate_const_key / rvs_rate_const_value) rate constants.
    A conflict is flagged when the same key appears with two or more distinct
    numeric values in any combination of reactions or directions.
    """
    param_assignments: dict[str, list[tuple[str, str, float]]] = defaultdict(list)

    for rxn in reactions:
        fwd_key = getattr(rxn, "rate_const_key", None)
        if fwd_key is not None and rxn.rate_const_value is not None:
            param_assignments[fwd_key].append((rxn.rxn_name, "fwd", float(rxn.rate_const_value)))
        rvs_key = getattr(rxn, "rvs_rate_const_key", None)
        if rvs_key is not None and rxn.rvs_rate_const_value is not None:
            param_assignments[rvs_key].append((rxn.rxn_name, "rvs", float(rxn.rvs_rate_const_value)))

    results: list[ParamConflictResult] = []
    for param_name, assignments in sorted(param_assignments.items()):
        distinct_values = {val for _, _, val in assignments}
        if len(distinct_values) > 1:
            results.append(ParamConflictResult(param_name=param_name, assignments=assignments))

    return results


def print_parameter_conflict_report(results: list[ParamConflictResult]) -> None:
    """Print the parameter conflict report."""
    _section("PARAMETER CONFLICT CHECK")
    if not results:
        print("  No parameter conflicts ✓")
        return
    print(f"  {len(results)} parameter(s) assigned different values across reactions:")
    rows = []
    for r in results:
        distinct_values = sorted({val for _, _, val in r.assignments})
        for rxn_name, direction, val in r.assignments:
            rows.append({
                "param_name": r.param_name,
                "distinct_values": str(distinct_values),
                "rxn_name": rxn_name,
                "direction": direction,
                "value": val,
            })
    _display_df(rows)


