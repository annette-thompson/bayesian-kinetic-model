# Check 4 — Name similarity
# ═══════════════════════════════════════════════════════════════════════════

def _similarity_pairs(
    names: list[str],
    threshold: float,
    kind: str,
    skip_substrings: bool = True,
) -> list[SimilarityWarning]:
    """Return SimilarityWarning entries for all pairs in *names* above *threshold*."""
    warnings: list[SimilarityWarning] = []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            if skip_substrings and (a in b or b in a):
                continue
            score = SequenceMatcher(None, a, b).ratio()
            if score >= threshold:
                if a.lower() == b.lower():
                    note = "capitalization mismatch"
                else:
                    note = f"high similarity ({score:.2f})"
                warnings.append(SimilarityWarning(family_a=a, family_b=b, score=score, note=note, kind=kind))
    return warnings


def check_name_similarity(
    reactions: list[_Reaction],
    threshold: float = DEFAULT_SIMILARITY_THRESHOLD,
) -> list[SimilarityWarning]:
    """Flag suspiciously similar species family names and parameter names.

    Species families are derived by stripping the C{N}_ chain prefix and _un
    suffix.  Pairs where one name is a substring of the other are skipped for
    species (naturally related names like FabB_Act / FabB_Act_MalACP) but not
    for parameters (short keys like k1f / k1r must still be compared).
    """
    all_species: set[str] = set()
    for rxn in reactions:
        all_species.update(rxn.reactants)
        all_species.update(rxn.products)

    families: set[str] = set()
    for sp in all_species:
        family, _, _ = _extract_family(sp)
        families.add(family)

    param_keys: set[str] = set()
    for rxn in reactions:
        fwd = getattr(rxn, "rate_const_key", None)
        rvs = getattr(rxn, "rvs_rate_const_key", None)
        if fwd:
            param_keys.add(fwd)
        if rvs:
            param_keys.add(rvs)

    warnings: list[SimilarityWarning] = (
        _similarity_pairs(sorted(families),   threshold, kind="species",   skip_substrings=True)
        + _similarity_pairs(sorted(param_keys), threshold, kind="parameter", skip_substrings=False)
    )
    return sorted(warnings, key=lambda w: (-w.score, w.kind))


def print_similarity_report(warnings: list[SimilarityWarning]) -> None:
    """Print the name-similarity report."""
    _section("NAME SIMILARITY CHECK")
    if not warnings:
        print("  No suspicious name pairs found ✓")
        return
    sp_warnings  = [w for w in warnings if w.kind == "species"]
    pm_warnings  = [w for w in warnings if w.kind == "parameter"]
    print(f"  {len(warnings)} suspicious pair(s): {len(sp_warnings)} species, {len(pm_warnings)} parameter")
    if sp_warnings:
        print()
        print("  Species families:")
        _display_df([
            {"name_a": w.family_a, "name_b": w.family_b, "score": f"{w.score:.2f}", "note": w.note}
            for w in sp_warnings
        ])
    if pm_warnings:
        print()
        print("  Parameter keys:")
        _display_df([
            {"name_a": w.family_a, "name_b": w.family_b, "score": f"{w.score:.2f}", "note": w.note}
            for w in pm_warnings
        ])


# ═══════════════════════════════════════════════════════════════════════════
# Check 5 — Zero-rate reactions
# ═══════════════════════════════════════════════════════════════════════════

def check_zero_rates(reactions: list[_Reaction]) -> list[ZeroRateResult]:
    """Flag any reactions with a zero forward or reverse rate constant."""
    results: list[ZeroRateResult] = []
    for rxn in reactions:
        fwd_zero = rxn.rate_const_value == 0.0
        rvs_zero = rxn.reversible and rxn.rvs_rate_const_value == 0.0
        if fwd_zero and rvs_zero:
            direction = "both"
        elif fwd_zero:
            direction = "forward"
        elif rvs_zero:
            direction = "reverse"
        else:
            continue
        results.append(
            ZeroRateResult(
                rxn_name=rxn.rxn_name,
                expression=rxn.reaction_expression(),
                direction=direction,
            )
        )
    return results


def print_zero_rate_report(results: list[ZeroRateResult]) -> None:
    """Print the zero-rate reactions report."""
    _section("ZERO-RATE REACTIONS")
    if not results:
        print("  No zero-rate reactions ✓")
        return
    print(f"  {len(results)} reaction(s) with at least one zero rate constant:")
    _display_df([
        {"rxn_name": r.rxn_name, "direction": r.direction, "expression": r.expression}
        for r in results
    ])


# ═══════════════════════════════════════════════════════════════════════════
# Check 6 — Irreversible accumulation / drain
# ═══════════════════════════════════════════════════════════════════════════

def check_irreversible_flow(reactions: list[_Reaction]) -> IrreversibleFlowResult:
    """Flag species with a one-way irreversible flow imbalance.

    A species is *fully generated* across the network if it appears as
    a forward product of any reaction, OR as a reactant in any reversible
    reaction (the reverse direction generates it).  Likewise it is *fully
    consumed* if it appears as a forward reactant of any reaction OR as a
    product in any reversible reaction (the reverse direction consumes it).

    Two situations are flagged:
    - **Irreversibly generated, never consumed** — produced by ≥1 irreversible
      forward reaction AND not consumed anywhere (neither as a fwd reactant
      nor via any reverse direction).  Will accumulate without bound.
    - **Irreversibly consumed, never generated** — consumed by ≥1 irreversible
      forward reaction AND not generated anywhere (neither as a fwd product
      nor via any reverse direction).  Will drain to zero.
    """
    # Full generation set: fwd products + reactants of reversible rxns
    full_generated: set[str] = set()
    # Full consumption set: fwd reactants + products of reversible rxns
    full_consumed: set[str] = set()
    # Irreversible-only maps: species → list of responsible rxn_names
    irrev_gen_rxns: dict[str, list[str]] = defaultdict(list)
    irrev_con_rxns: dict[str, list[str]] = defaultdict(list)

    for rxn in reactions:
        for sp in rxn.products:
            full_generated.add(sp)
            if not rxn.reversible:
                irrev_gen_rxns[sp].append(rxn.rxn_name)
        for sp in rxn.reactants:
            full_consumed.add(sp)
            if not rxn.reversible:
                irrev_con_rxns[sp].append(rxn.rxn_name)
        if rxn.reversible:
            # Reverse direction: reactants are generated, products are consumed
            for sp in rxn.reactants:
                full_generated.add(sp)
            for sp in rxn.products:
                full_consumed.add(sp)

    irrev_gen_never_consumed = sorted(
        [(sp, rxns) for sp, rxns in irrev_gen_rxns.items() if sp not in full_consumed],
        key=lambda x: x[0],
    )
    irrev_consumed_never_gen = sorted(
        [(sp, rxns) for sp, rxns in irrev_con_rxns.items() if sp not in full_generated],
        key=lambda x: x[0],
    )

    return IrreversibleFlowResult(
        irrev_gen_never_consumed=irrev_gen_never_consumed,
        irrev_consumed_never_gen=irrev_consumed_never_gen,
    )


def print_irreversible_flow_report(result: IrreversibleFlowResult) -> None:
    """Print the irreversible accumulation / drain report."""
    _section("IRREVERSIBLE ACCUMULATION AND DRAIN CHECK")
    acc = result.irrev_gen_never_consumed
    drn = result.irrev_consumed_never_gen
    print(f"  Irreversibly generated, never consumed: {len(acc)}")
    print(f"  Irreversibly consumed, never generated: {len(drn)}")
    if not acc and not drn:
        print("  No irreversible accumulation or drain issues ✓")
        return
    if acc:
        print()
        print("  [ACCUMULATE] Generated by irreversible reaction(s) but never consumed:")
        _display_df([
            {"species": sp, "source_reactions": ", ".join(rxn_names)}
            for sp, rxn_names in acc
        ])
    if drn:
        print()
        print("  [DRAIN] Consumed by irreversible reaction(s) but never generated:")
        _display_df([
            {"species": sp, "consuming_reactions": ", ".join(rxn_names)}
            for sp, rxn_names in drn
        ])


